"""Compatibilidade da camada PostgreSQL sem exigir um servidor no teste local."""
import sqlite3

from backend import database
from backend.security import INCREMENT_LOGIN_ATTEMPT_SQL


class FakeCursor:
    def __init__(self, columns=(), rows=()):
        self.description = [type("Column", (), {"name": name})() for name in columns] if columns else None
        self.rows = list(rows)

    def fetchone(self):
        return self.rows.pop(0) if self.rows else None

    def fetchall(self):
        result, self.rows = self.rows, []
        return result

    def __iter__(self):
        while self.rows:
            yield self.rows.pop(0)


class FakeConnection:
    def __init__(self):
        self.calls = []
        self.commits = 0
        self.rollbacks = 0
        self.closed = False

    def execute(self, sql, params=()):
        self.calls.append((sql, params))
        if "RETURNING id" in sql:
            return FakeCursor(("id",), ((17,),))
        return FakeCursor(("id", "nome"), ((4, "Teste"),))

    def commit(self):
        self.commits += 1

    def rollback(self):
        self.rollbacks += 1

    def close(self):
        self.closed = True


def test_postgres_rows_support_names_indices_and_mapping():
    row = database.PostgresRow(("id", "nome"), (4, "Teste"))
    assert row[0] == row["id"] == 4
    assert dict(row) == {"id": 4, "nome": "Teste"}


def test_postgres_adapter_translates_parameters_and_returns_insert_id():
    raw = FakeConnection()
    db = database.PostgresConnection(raw)
    row = db.execute("SELECT id,nome FROM usuarios WHERE id=?", (4,)).fetchone()
    assert dict(row) == {"id": 4, "nome": "Teste"}
    assert raw.calls[0] == ("SELECT id,nome FROM usuarios WHERE id=%s", (4,))
    result = db.execute("INSERT INTO usuarios(nome,login,senha_hash) VALUES (?,?,?)",
                        ("Teste", "teste", "hash"))
    assert result.lastrowid == 17
    assert raw.calls[1][0].endswith("VALUES (%s,%s,%s) RETURNING id")


def test_postgres_write_transaction_serializes_and_closes(monkeypatch):
    raw = FakeConnection()
    monkeypatch.setattr(database, "connect", lambda: database.PostgresConnection(raw))
    with database.transaction(write=True) as db:
        assert db.execute("SELECT id,nome FROM usuarios").fetchall()[0]["nome"] == "Teste"
    assert raw.calls[0][0] == "SELECT pg_advisory_xact_lock(67202601)"
    assert raw.commits == 1 and raw.rollbacks == 0 and raw.closed


def test_postgres_transaction_rolls_back_on_error(monkeypatch):
    raw = FakeConnection()
    monkeypatch.setattr(database, "connect", lambda: database.PostgresConnection(raw))
    try:
        with database.transaction(write=True):
            raise ValueError("falha")
    except ValueError:
        pass
    assert raw.commits == 0 and raw.rollbacks == 1 and raw.closed


def test_postgres_schema_keeps_required_tables_and_constraints():
    schema = (database.ROOT / "backend" / "schema_postgres.sql").read_text(encoding="utf-8")
    for name in ("usuarios", "sessoes", "hospedes", "enderecos", "quartos", "reservas",
                 "acompanhantes", "pagamentos", "auditoria"):
        assert f"CREATE TABLE IF NOT EXISTS {name}" in schema
    assert "GENERATED BY DEFAULT AS IDENTITY" in schema
    assert "PRAGMA" not in schema


def test_login_attempt_upsert_is_unambiguous_and_works_in_sqlite():
    assert "tentativas_login.quantidade+1" in INCREMENT_LOGIN_ATTEMPT_SQL
    db = sqlite3.connect(":memory:")
    try:
        db.execute("CREATE TABLE tentativas_login(chave TEXT PRIMARY KEY, quantidade INTEGER, inicio INTEGER)")
        for _ in range(2):
            db.execute(INCREMENT_LOGIN_ATTEMPT_SQL, ("origem", 123))
        assert db.execute("SELECT quantidade FROM tentativas_login WHERE chave='origem'").fetchone()[0] == 2
    finally:
        db.close()

CREATE TABLE IF NOT EXISTS usuarios (
 id INTEGER PRIMARY KEY, nome TEXT NOT NULL, login TEXT NOT NULL UNIQUE,
 senha_hash TEXT NOT NULL, ativo INTEGER NOT NULL DEFAULT 1 CHECK(ativo IN (0,1))
);
CREATE TABLE IF NOT EXISTS sessoes (
 token_hash TEXT PRIMARY KEY, usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
 csrf TEXT NOT NULL, expira INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS codigos_recuperacao (
 usuario_id INTEGER PRIMARY KEY REFERENCES usuarios(id) ON DELETE CASCADE,
 codigo_hash TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS tentativas_login (
 chave TEXT PRIMARY KEY, quantidade INTEGER NOT NULL, inicio INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS hospedes (
 id INTEGER PRIMARY KEY, nome TEXT NOT NULL, cpf TEXT NOT NULL UNIQUE,
 nascimento TEXT NOT NULL, email TEXT NOT NULL, telefone TEXT NOT NULL,
 genero TEXT NOT NULL DEFAULT '', nacionalidade TEXT NOT NULL DEFAULT 'Brasileira',
 observacoes TEXT NOT NULL DEFAULT '', ativo INTEGER NOT NULL DEFAULT 1 CHECK(ativo IN (0,1)),
 criado_em TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS enderecos (
 id INTEGER PRIMARY KEY, hospede_id INTEGER NOT NULL UNIQUE REFERENCES hospedes(id) ON DELETE CASCADE,
 cep TEXT NOT NULL, logradouro TEXT NOT NULL, numero TEXT NOT NULL,
 complemento TEXT NOT NULL DEFAULT '', bairro TEXT NOT NULL, cidade TEXT NOT NULL,
 estado TEXT NOT NULL, pais TEXT NOT NULL DEFAULT 'Brasil'
);
CREATE TABLE IF NOT EXISTS quartos (
 id INTEGER PRIMARY KEY, numero INTEGER NOT NULL CHECK(numero>0), predio INTEGER NOT NULL CHECK(predio>0),
 andar INTEGER NOT NULL DEFAULT 0,
 capacidade INTEGER NOT NULL CHECK(capacidade BETWEEN 1 AND 30),
 diaria_centavos INTEGER NOT NULL CHECK(diaria_centavos>0),
 status TEXT NOT NULL DEFAULT 'DISPONIVEL' CHECK(status IN ('DISPONIVEL','MANUTENCAO')),
 descricao TEXT NOT NULL DEFAULT '', acessivel INTEGER NOT NULL DEFAULT 0 CHECK(acessivel IN (0,1)),
 ativo INTEGER NOT NULL DEFAULT 1 CHECK(ativo IN (0,1)), UNIQUE(predio,numero)
);
CREATE TABLE IF NOT EXISTS reservas (
 id INTEGER PRIMARY KEY, codigo TEXT NOT NULL UNIQUE,
 hospede_id INTEGER NOT NULL REFERENCES hospedes(id), quarto_id INTEGER NOT NULL REFERENCES quartos(id),
 entrada TEXT NOT NULL, saida TEXT NOT NULL CHECK(saida>entrada),
 quantidade INTEGER NOT NULL CHECK(quantidade BETWEEN 1 AND 30),
 diaria_centavos INTEGER NOT NULL CHECK(diaria_centavos>0),
 desconto_centavos INTEGER NOT NULL DEFAULT 0 CHECK(desconto_centavos>=0),
 total_centavos INTEGER NOT NULL CHECK(total_centavos>=0),
 status TEXT NOT NULL DEFAULT 'CONFIRMADA' CHECK(status IN ('CONFIRMADA','HOSPEDADA','FINALIZADA','CANCELADA')),
 observacoes TEXT NOT NULL DEFAULT '', criado_em TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
 checkin_em TEXT, checkout_em TEXT
);
CREATE INDEX IF NOT EXISTS idx_reservas_periodo ON reservas(quarto_id,status,entrada,saida);
CREATE INDEX IF NOT EXISTS idx_reservas_hospede ON reservas(hospede_id);
CREATE TABLE IF NOT EXISTS acompanhantes (
 id INTEGER PRIMARY KEY, reserva_id INTEGER NOT NULL REFERENCES reservas(id) ON DELETE CASCADE,
 nome TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS pagamentos (
 id INTEGER PRIMARY KEY, reserva_id INTEGER NOT NULL REFERENCES reservas(id),
 valor_centavos INTEGER NOT NULL CHECK(valor_centavos>0),
 forma TEXT NOT NULL CHECK(forma IN ('PIX','DINHEIRO','CARTAO','TRANSFERENCIA')),
 status TEXT NOT NULL DEFAULT 'PAGO' CHECK(status IN ('PAGO','ESTORNADO')),
 registrado_em TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, estornado_em TEXT,
 motivo_estorno TEXT, usuario_id INTEGER NOT NULL REFERENCES usuarios(id)
);
CREATE TABLE IF NOT EXISTS auditoria (
 id INTEGER PRIMARY KEY, usuario_id INTEGER REFERENCES usuarios(id), acao TEXT NOT NULL,
 entidade TEXT NOT NULL, registro_id INTEGER, criado_em TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
